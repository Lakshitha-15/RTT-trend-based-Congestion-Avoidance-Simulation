#!/usr/bin/env python3
"""
analyze.py -- turn the measured metrics into tables and figures.

  python3 analysis/analyze.py --config configs/main.json
  python3 analysis/analyze.py --config configs/sensitivity.json

Reads   data/processed/<suite>/metrics_per_run.csv   (written by experiments/run_experiments.py)
        data/raw/<suite>/<scenario>/<algo>/run1/     (kept raw traces, for time-series figures)
Writes  data/processed/<suite>/summary_by_scenario.csv, paired_differences.csv, RESULTS.md
        plots/<suite>/*.png   and   plots/<suite>/scenarios/<scenario>/*.png
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import interpret  # noqa: E402
import metrics as M  # noqa: E402
import plotting as P  # noqa: E402

# metric -> lower_is_better (None = neutral)
DIRECTION = {
    "rtt_mean_ms": True, "rtt_median_ms": True, "rtt_p95_ms": True, "rtt_max_ms": True,
    "qdelay_mean_ms": True, "qdelay_p95_ms": True, "rtt_slope_abs_mean": True,
    "goodput_mbps": False, "utilization_pct": False, "loss_rate_pct": True, "drops_total": True,
    "drops_window": True, "retx_total": True, "retx_window": True, "loss_events_window": True,
    "cwnd_mean_segs": None, "cwnd_max_segs": None, "queue_mean_pkts": True, "queue_p95_pkts": True,
    "fairness_jain": False,
}
SUMMARY_METRICS = list(DIRECTION) + ["loss_events_total", "frac_early", "frac_congested", "early_entries",
                                     "delay_congested_entries", "first_warning_s", "first_loss_s",
                                     "warned_loss_frac", "lead_median_s", "n_flows", "rtt_std_ms"]
COMPARISONS = [("proposed", "baseline"), ("noslope", "baseline"), ("proposed", "noslope")]
BAR_KEYS = ["rtt_mean_ms", "rtt_p95_ms", "rtt_max_ms", "goodput_mbps", "loss_rate_pct", "retx_window",
            "cwnd_mean_segs", "cwnd_max_segs", "queue_mean_pkts"]
PAIR_KEYS = ["rtt_mean_ms", "rtt_p95_ms", "goodput_mbps", "loss_events_window", "retx_window",
             "queue_mean_pkts", "cwnd_mean_segs", "fairness_jain", "utilization_pct"]


def summarize(df):
    rows = []
    for (sc, algo), g in df.groupby(["scenario", "algo"]):
        r = {"scenario": sc, "algo": algo, "runs": len(g)}
        for m in SUMMARY_METRICS:
            if m in g:
                r[m + "_mean"] = g[m].mean()
                r[m + "_std"] = g[m].std(ddof=1) if len(g) > 1 else float("nan")
                r[m + "_min"] = g[m].min()
                r[m + "_max"] = g[m].max()
        rows.append(r)
    return pd.DataFrame(rows)


def paired_table(df, scenarios):
    rows = []
    for sc in scenarios:
        for a, b in COMPARISONS:
            A = df[(df.scenario == sc) & (df.algo == a)].set_index("run")
            B = df[(df.scenario == sc) & (df.algo == b)].set_index("run")
            common = A.index.intersection(B.index)
            if len(common) == 0:
                continue
            for k, lower in DIRECTION.items():
                d = (A.loc[common, k] - B.loc[common, k]).to_numpy()
                mean, lo, hi, n = paired_ci(d)
                bm = B.loc[common, k].mean()
                if not np.isfinite(lo) or lo <= 0 <= hi:
                    verdict = "no clear difference"
                elif lower is None:
                    verdict = "changed (neutral metric)"
                else:
                    verdict = f"{a} better" if ((mean < 0) == lower) else f"{a} worse"
                rows.append({"scenario": sc, "comparison": f"{a}-{b}", "metric": k, "baseline_mean": bm,
                             "proposed_mean": A.loc[common, k].mean(), "diff_mean": mean, "ci95_lo": lo,
                             "ci95_hi": hi, "rel_change_pct": 100 * mean / bm if bm else float("nan"),
                             "n_pairs": n, "verdict": verdict})
    return pd.DataFrame(rows)


paired_ci = M.paired_ci


def savefig(fig, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fig.savefig(path, dpi=130)
    import matplotlib.pyplot as plt
    plt.close(fig)


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(lines)


def write_results_md(path, cfg, summary, paired, scenarios):
    S = summary.set_index(["scenario", "algo"])
    out = [f"# Measured results: suite `{cfg['name']}`\n",
           "Generated by `analysis/analyze.py` from `metrics_per_run.csv`. Values are means over runs "
           "(steady-state window after warm-up). Nothing here is typed by hand.\n"]
    algos = [a for a in ("baseline", "proposed", "noslope") if a in summary.algo.unique()]
    for key, title, dec in (("rtt_mean_ms", "Mean RTT [ms]", 1), ("rtt_p95_ms", "95th percentile RTT [ms]", 1),
                            ("rtt_max_ms", "Maximum RTT [ms]", 1), ("goodput_mbps", "Goodput [Mbit/s]", 2),
                            ("loss_rate_pct", "Packet loss rate, whole run [%]", 3),
                            ("loss_events_window", "Loss-recovery events, steady state (per run)", 1),
                            ("retx_window", "Retransmitted segments, steady state (per run)", 1),
                            ("cwnd_mean_segs", "Mean cwnd [segments]", 1), ("cwnd_max_segs", "Max cwnd [segments]", 1),
                            ("queue_mean_pkts", "Mean queue [packets]", 1), ("fairness_jain", "Jain fairness", 3)):
        rows = []
        for sc in scenarios:
            r = {"scenario": sc}
            for a in algos:
                if (sc, a) in S.index:
                    r[a] = f"{S.loc[(sc, a), key + '_mean']:.{dec}f} +- {S.loc[(sc, a), key + '_std']:.{dec}f}"
            rows.append(r)
        out.append(f"## {title}\n\n" + md_table(pd.DataFrame(rows)) + "\n")
    out.append("## Paired comparison proposed vs baseline (verdict from the 95% interval of the paired difference)\n")
    pt = paired[(paired.comparison == "proposed-baseline") & paired.metric.isin(PAIR_KEYS)].copy()
    pt = pt[["scenario", "metric", "baseline_mean", "proposed_mean", "rel_change_pct", "ci95_lo", "ci95_hi", "verdict"]]
    out.append(md_table(pt.round(3)) + "\n")
    out.append("## Verdict tally (proposed vs baseline, all scenario x metric pairs)\n")
    out.append(md_table(paired[paired.comparison == "proposed-baseline"].verdict.value_counts().rename_axis("verdict")
                        .reset_index(name="count")) + "\n")
    out.append("## Automatic interpretation per scenario\n")
    for sc in scenarios:
        out.append(f"### {sc}: {cfg['scenarios'][sc]['description']}\n")
        for line in interpret.describe(paired, sc) + interpret.observations(paired, summary, sc):
            out.append(f"- {line}")
        out.append("")
    open(path, "w").write("\n".join(out))


def run_dirs(raw_root, scen, algos, run=1):
    d = {}
    for a in algos:
        p = os.path.join(raw_root, scen, a, f"run{run}")
        if M.has_run(p):
            d[a] = p
    return d


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", required=True)
    ap.add_argument("--data-dir", default=os.path.join(ROOT, "data"))
    ap.add_argument("--plots-dir", default=os.path.join(ROOT, "plots"))
    ap.add_argument("--no-scenario-plots", action="store_true")
    a = ap.parse_args()

    cfg = json.load(open(a.config))
    suite = cfg["name"]
    proc = os.path.join(a.data_dir, "processed", suite)
    raw = os.path.join(a.data_dir, "raw", suite)
    plots = os.path.join(a.plots_dir, suite)
    df = pd.read_csv(os.path.join(proc, "metrics_per_run.csv"))
    scenarios = [s for s in cfg["scenarios"] if s in set(df.scenario)]
    summary = summarize(df)
    summary.to_csv(os.path.join(proc, "summary_by_scenario.csv"), index=False)
    pd.set_option("display.width", 220)
    pd.set_option("display.max_rows", 500)

    if cfg["type"] == "sensitivity":
        for sc in scenarios:
            savefig(P.fig_sensitivity(summary, sc), os.path.join(plots, f"sensitivity_{sc}.png"))
        cols = ["scenario", "algo", "runs", "rtt_mean_ms_mean", "utilization_pct_mean", "loss_events_window_mean",
                "fairness_jain_mean", "frac_early_mean", "early_entries_mean"]
        print(summary[cols].round(2).to_string(index=False))
        print(f"\nFigures in {plots}/")
        return

    paired = paired_table(df, scenarios)
    paired.to_csv(os.path.join(proc, "paired_differences.csv"), index=False)
    write_results_md(os.path.join(proc, "RESULTS.md"), cfg, summary, paired, scenarios)

    savefig(P.fig_summary_bars(summary, scenarios, BAR_KEYS), os.path.join(plots, "summary_bars.png"))
    savefig(P.fig_paired(paired, scenarios, PAIR_KEYS), os.path.join(plots, "paired_proposed_vs_baseline.png"))
    savefig(P.fig_paired(paired, scenarios, ["rtt_mean_ms", "rtt_p95_ms", "goodput_mbps", "loss_events_window",
                                             "queue_mean_pkts", "fairness_jain"], "proposed-noslope"),
            os.path.join(plots, "paired_proposed_vs_noslope.png"))
    savefig(P.fig_tradeoff(summary, scenarios), os.path.join(plots, "tradeoff_delay_vs_utilization.png"))
    if "monitor" in summary.algo.unique():
        savefig(P.fig_detection(summary, scenarios), os.path.join(plots, "detection_monitor.png"))
    if not a.no_scenario_plots:
        for sc in scenarios:
            runs = run_dirs(raw, sc, ["baseline", "proposed", "noslope"])
            trend_runs = run_dirs(raw, sc, ["monitor", "proposed", "noslope"])
            if "baseline" not in runs:
                continue
            out = os.path.join(plots, "scenarios", sc)
            savefig(P.fig_rtt(runs, 0, f"({sc}, run 1, flow 0)"), os.path.join(out, "rtt.png"))
            savefig(P.fig_trend(trend_runs, 0, f"({sc}, run 1, flow 0)"), os.path.join(out, "trend_state.png"))
            savefig(P.fig_cwnd(runs, 0, f"({sc}, run 1, flow 0)"), os.path.join(out, "cwnd.png"))
            savefig(P.fig_throughput_loss(runs, f"({sc}, run 1)"), os.path.join(out, "throughput_loss.png"))
            savefig(P.fig_queue(runs, f"({sc}, run 1)"), os.path.join(out, "queue.png"))

    print(f"Runs analysed: {len(df)} over {len(scenarios)} scenarios.\n")
    for k in ("rtt_mean_ms", "rtt_p95_ms", "goodput_mbps", "loss_events_window", "fairness_jain"):
        t = paired[(paired.comparison == "proposed-baseline") & (paired.metric == k)]
        print(f"=== {P.METRIC_LABEL[k]}: proposed - baseline ===")
        print(t[["scenario", "baseline_mean", "proposed_mean", "rel_change_pct", "ci95_lo", "ci95_hi", "verdict"]]
              .round(3).to_string(index=False), "\n")
    print("Verdict tally (proposed vs baseline):")
    print(paired[paired.comparison == "proposed-baseline"].verdict.value_counts().to_string())
    print(f"\nTables: {proc}/   Figures: {plots}/")


if __name__ == "__main__":
    main()
